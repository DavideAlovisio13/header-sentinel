"""Rendering: terminal, JSON, Markdown and HTML reports."""

from __future__ import annotations

import html
import json

_ICON = {"ok": "+", "warn": "!", "missing": "x"}
_COLOR = {"ok": "\033[32m", "warn": "\033[33m", "missing": "\033[31m"}
_RESET = "\033[0m"
_GRADE_COLOR = {"A": "\033[32m", "B": "\033[32m", "C": "\033[33m", "D": "\033[33m", "F": "\033[31m"}


def render_terminal(result: dict, target: str, color: bool = True) -> str:
    def c(code: str) -> str:
        return code if color else ""

    lines = []
    grade = result["grade"]
    gcol = _GRADE_COLOR.get(grade, "")
    lines.append("")
    lines.append(f"  Security headers report  -  {target}")
    lines.append(f"  Score: {result['score']}/100   Grade: {c(gcol)}{grade}{c(_RESET)}")
    s = result["summary"]
    lines.append(f"  ({s['ok']} ok, {s['warn']} warnings, {s['missing']} missing)")
    lines.append("")
    for chk in result["checks"]:
        icon = _ICON[chk["status"]]
        col = _COLOR[chk["status"]] if color else ""
        lines.append(f"  {c(col)}[{icon}]{c(_RESET)} {chk['name']:<32} {chk['points']:>4}/{chk['max']:<3}  {chk['note']}")
    if result["info_leaks"]:
        lines.append("")
        lines.append("  Information disclosure:")
        for il in result["info_leaks"]:
            lines.append(f"    - {il['header']}: {il['value']}")
    if result["cookies"]:
        lines.append("")
        lines.append("  Cookie flags:")
        for ck in result["cookies"]:
            lines.append(f"    - {ck['cookie']}: {', '.join(ck['issues'])}")
    lines.append("")
    return "\n".join(lines)


def to_json(result: dict, target: str) -> str:
    out = dict(result)
    out["target"] = target
    return json.dumps(out, indent=2)


def to_markdown(result: dict, target: str) -> str:
    md = [f"# Security headers report — `{target}`", ""]
    md.append(f"**Score:** {result['score']}/100 &nbsp; **Grade:** {result['grade']}")
    s = result["summary"]
    md.append(f"\n{s['ok']} ok · {s['warn']} warnings · {s['missing']} missing\n")
    md.append("| Status | Header | Points | Note |")
    md.append("|:------:|--------|:------:|------|")
    for chk in result["checks"]:
        md.append(f"| {chk['status']} | `{chk['name']}` | {chk['points']}/{chk['max']} | {chk['note']} |")
    if result["info_leaks"]:
        md.append("\n## Information disclosure\n")
        for il in result["info_leaks"]:
            md.append(f"- `{il['header']}`: {il['value']}")
    if result["cookies"]:
        md.append("\n## Cookie flags\n")
        for ck in result["cookies"]:
            md.append(f"- `{ck['cookie']}`: {', '.join(ck['issues'])}")
    md.append("")
    return "\n".join(md)


def to_html(result: dict, target: str) -> str:
    rows = ""
    badge = {"ok": "#16a34a", "warn": "#d97706", "missing": "#dc2626"}
    for chk in result["checks"]:
        rows += (
            f"<tr><td><span style='color:{badge[chk['status']]}'>&#9679;</span> {chk['status']}</td>"
            f"<td><code>{html.escape(chk['name'])}</code></td>"
            f"<td>{chk['points']}/{chk['max']}</td>"
            f"<td>{html.escape(chk['note'])}</td></tr>"
        )
    gcol = {"A": "#16a34a", "B": "#16a34a", "C": "#d97706", "D": "#d97706", "F": "#dc2626"}.get(result["grade"], "#333")
    leaks = "".join(f"<li><code>{html.escape(i['header'])}</code>: {html.escape(i['value'])}</li>" for i in result["info_leaks"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Security headers report - {html.escape(target)}</title>
<style>
body{{font:15px/1.5 system-ui,Segoe UI,Arial,sans-serif;max-width:900px;margin:40px auto;padding:0 16px;color:#111}}
h1{{font-size:20px}} .grade{{font-size:48px;font-weight:800;color:{gcol}}}
table{{width:100%;border-collapse:collapse;margin-top:16px}} td,th{{text-align:left;padding:8px;border-bottom:1px solid #eee}}
code{{background:#f4f4f5;padding:1px 5px;border-radius:5px}}
.muted{{color:#666}}
</style></head><body>
<h1>Security headers report</h1>
<p class="muted">{html.escape(target)}</p>
<p><span class="grade">{result['grade']}</span> &nbsp; <b>{result['score']}/100</b></p>
<table><thead><tr><th>Status</th><th>Header</th><th>Points</th><th>Note</th></tr></thead>
<tbody>{rows}</tbody></table>
{('<h2>Information disclosure</h2><ul>' + leaks + '</ul>') if leaks else ''}
<p class="muted">Generated by header-sentinel.</p>
</body></html>"""
